#!/usr/bin/env python3
"""Generate a compact kernel symbol table from the linked ELF image.

The kernel keeps no runtime copy of its own ELF file, so the symbol table is
extracted from an initial link and embedded into a second link. The generated
object is placed after the original input objects; text addresses are therefore
unchanged between the two links.
"""
import struct
import subprocess
import sys
from pathlib import Path

ELFCLASS64 = 2
ELFDATA2LSB = 1
SHT_SYMTAB = 2
STT_NOTYPE = 0
STT_FUNC = 2
STT_GNU_IFUNC = 10
SHN_UNDEF = 0


def read_elf(path):
    data = Path(path).read_bytes()
    if data[:4] != b"\x7fELF" or data[4] != ELFCLASS64 or data[5] != ELFDATA2LSB:
        raise RuntimeError("expected a little-endian ELF64 image")

    fields = struct.unpack_from("<HHIQQQIHHHHHH", data, 16)
    (_, _, _, _, _, shoff, _, _, _, _, shentsize, shnum, shstrndx) = fields
    sections = []
    for i in range(shnum):
        values = struct.unpack_from("<IIQQQQIIQQ", data, shoff + i * shentsize)
        (name, kind, flags, address, offset, size, link, info, align, entsize) = values
        sections.append({
            "name_offset": name,
            "type": kind,
            "address": address,
            "offset": offset,
            "size": size,
            "link": link,
            "entsize": entsize,
        })

    shstr = sections[shstrndx]
    shstr_data = data[shstr["offset"]:shstr["offset"] + shstr["size"]]

    def string_at(table, offset):
        end = table.find(b"\0", offset)
        if end < 0:
            end = len(table)
        return table[offset:end].decode("utf-8", errors="replace")

    for section in sections:
        section["name"] = string_at(shstr_data, section["name_offset"])
    return data, sections


def function_symbols(data, sections):
    text = next((s for s in sections if s["name"] == ".text"), None)
    if text is None:
        raise RuntimeError("no .text section in the ELF image")
    text_start = text["address"]
    text_end = text["address"] + text["size"]

    symtab = next((s for s in sections if s["type"] == SHT_SYMTAB), None)
    if symtab is None:
        raise RuntimeError("no .symtab section in the ELF image")
    strtab = sections[symtab["link"]]
    strings = data[strtab["offset"]:strtab["offset"] + strtab["size"]]

    symbols = []
    entry_size = symtab["entsize"] or 24
    count = symtab["size"] // entry_size
    for i in range(count):
        offset = symtab["offset"] + i * entry_size
        name_offset, info, _, shndx, value, size = struct.unpack_from("<IBBHQQ", data, offset)
        kind = info & 0xF
        if shndx == SHN_UNDEF or value == 0:
            continue
        in_text = text_start <= value < text_end
        if kind not in (STT_FUNC, STT_GNU_IFUNC) and not (kind == STT_NOTYPE and in_text):
            continue
        end = strings.find(b"\0", name_offset)
        if end < 0:
            end = len(strings)
        name = strings[name_offset:end].decode("utf-8", errors="replace")
        if name:
            symbols.append((value, size, name))

    symbols.sort(key=lambda item: (item[0], item[2]))
    return symbols


def demangle(names):
    try:
        result = subprocess.run(
            ["c++filt"], input="\n".join(names), text=True,
            capture_output=True, check=True)
    except (FileNotFoundError, subprocess.CalledProcessError):
        return names
    demangled = result.stdout.splitlines()
    return demangled if len(demangled) == len(names) else names


def c_string(text):
    escaped = []
    for character in text:
        code = ord(character)
        if character == "\\":
            escaped.append("\\\\")
        elif character == '"':
            escaped.append('\\"')
        elif 32 <= code < 127:
            escaped.append(character)
        else:
            escaped.append("?")
    return '"' + "".join(escaped) + '"'


def main():
    if len(sys.argv) != 3:
        print(f"usage: {sys.argv[0]} <kernel.elf> <output.cpp>", file=sys.stderr)
        return 2

    data, sections = read_elf(sys.argv[1])
    symbols = function_symbols(data, sections)
    names = demangle([symbol[2] for symbol in symbols])

    lines = [
        "// Generated by scripts/gen-symbols.py. Do not edit.",
        "#include <lib/symbols.hpp>",
        "",
        "namespace nord {",
        "",
        'extern "C" const KernelSymbol __kernel_symbols[]',
        '    __attribute__((section(".kernel_symbols"), used, aligned(8))) = {',
    ]
    for (address, size, _), name in zip(symbols, names):
        lines.append(f"    {{0x{address:016x}ULL, 0x{size:016x}ULL, {c_string(name)}}},")
    lines += [
        "};",
        "",
        'extern "C" const u64 __kernel_symbol_count',
        '    __attribute__((section(".kernel_symbols"), used, aligned(8))) = ',
        f"    0x{len(symbols):016x}ULL;",
        "",
        "}",
        "",
    ]

    output = Path(sys.argv[2])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines))
    print(f"  SYM   {sys.argv[1]} -> {output} ({len(symbols)} symbols)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
